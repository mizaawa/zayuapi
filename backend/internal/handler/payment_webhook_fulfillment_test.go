// Exercise the signed HTTP notification through the real redeem and user
// repositories. Short redeem-code stubs conceal validation failures for the
// 39-character PAY- codes generated by the payment order service.
func TestEasyPayWebhookFulfillsGeneratedRechargeCodeWithRealRepositories(t *testing.T) {
	for _, initialStatus := range []string{service.OrderStatusPending, service.OrderStatusFailed} {
		for _, method := range []string{http.MethodGet, http.MethodPost} {
			t.Run(initialStatus+"/"+method, func(t *testing.T) {
				h, client, order, key := newEasyPayWebhookFulfillmentFixture(t, initialStatus)
				ctx := context.Background()
				user, err := client.User.Get(ctx, order.UserID)
				require.NoError(t, err)
				require.Equal(t, 12.0, user.Balance)
				require.Equal(t, initialStatus, order.Status)
				beforeCodes, err := client.RedeemCode.Query().Count(ctx)
				require.NoError(t, err)
				require.Zero(t, beforeCodes)

				payload := genuineEasyPayWebhookTestValues(order)
				payload.Set("money", "10.00")
				payload.Set("sign", signEasyPayWebhookTestValues(payload, key))
				for i, notificationMethod := range []string{method, http.MethodGet, http.MethodPost, method} {
					response := sendEasyPayWebhookTestRequest(h, notificationMethod, payload.Encode())
					reloaded, err := client.PaymentOrder.Get(ctx, order.ID)
					require.NoError(t, err)
					user, err = client.User.Get(ctx, order.UserID)
					require.NoError(t, err)
					t.Logf("notification=%d method=%s http_status=%d body=%q code_length=%d order_status=%s paid_at=%t balance=%.2f",
						i, notificationMethod, response.Code, response.Body.String(), len(order.RechargeCode),
						reloaded.Status, reloaded.PaidAt != nil, user.Balance)
					require.Equal(t, http.StatusOK, response.Code, "notification %d: %s", i, response.Body.String())
					require.Equal(t, "success", response.Body.String())

					require.Equal(t, service.OrderStatusCompleted, reloaded.Status)
					require.Equal(t, "T1", reloaded.PaymentTradeNo)
					require.NotNil(t, reloaded.PaidAt)
					require.NotNil(t, reloaded.CompletedAt)
					require.Nil(t, reloaded.FailedAt)
					require.Nil(t, reloaded.FailedReason)
					if initialStatus == service.OrderStatusFailed {
						require.WithinDuration(t, *order.PaidAt, *reloaded.PaidAt, time.Microsecond,
							"retry preserves the original payment timestamp")
					}
					require.Equal(t, 22.0, user.Balance, "repeated notifications must credit only once")
					require.Equal(t, 10.0, user.TotalRecharged)

					code, err := client.RedeemCode.Query().Where(redeemcode.CodeEQ(order.RechargeCode)).Only(ctx)
					require.NoError(t, err)
					require.Equal(t, service.StatusUsed, code.Status)
					require.Equal(t, service.RedeemTypeBalance, code.Type)
					require.Equal(t, 10.0, code.Value)
					require.NotNil(t, code.UsedBy)
					require.Equal(t, order.UserID, *code.UsedBy)
					require.NotNil(t, code.UsedAt)
					codeCount, err := client.RedeemCode.Query().Count(ctx)
					require.NoError(t, err)
					require.Equal(t, 1, codeCount)
				}
			})
		}
	}
}

func TestEasyPayPaidFailedOrderRetryFulfillmentWithRealRepositories(t *testing.T) {
	h, client, order, _ := newEasyPayWebhookFulfillmentFixture(t, service.OrderStatusFailed)
	ctx := context.Background()
	for attempt := 0; attempt < 3; attempt++ {
		retryErr := h.paymentService.RetryFulfillment(ctx, order.ID)
		reloaded, err := client.PaymentOrder.Get(ctx, order.ID)
		require.NoError(t, err)
		user, err := client.User.Get(ctx, order.UserID)
		require.NoError(t, err)
		t.Logf("retry=%d error=%v code_length=%d order_status=%s paid_at=%t balance=%.2f",
			attempt, retryErr, len(order.RechargeCode), reloaded.Status, reloaded.PaidAt != nil, user.Balance)
		if attempt == 0 {
			require.NoError(t, retryErr)
		} else {
			require.ErrorContains(t, retryErr, "order already completed")
		}
		require.Equal(t, service.OrderStatusCompleted, reloaded.Status)
		require.Equal(t, "T1", reloaded.PaymentTradeNo)
		require.NotNil(t, reloaded.PaidAt)
		require.WithinDuration(t, *order.PaidAt, *reloaded.PaidAt, time.Microsecond)
		require.NotNil(t, reloaded.CompletedAt)
		require.Nil(t, reloaded.FailedAt)
		require.Nil(t, reloaded.FailedReason)
		require.Equal(t, 22.0, user.Balance)
		require.Equal(t, 10.0, user.TotalRecharged)
		code, err := client.RedeemCode.Query().Where(redeemcode.CodeEQ(order.RechargeCode)).Only(ctx)
		require.NoError(t, err)
		require.Equal(t, service.StatusUsed, code.Status)
		require.NotNil(t, code.UsedBy)
		require.Equal(t, order.UserID, *code.UsedBy)
		codeCount, err := client.RedeemCode.Query().Count(ctx)
		require.NoError(t, err)
		require.Equal(t, 1, codeCount)
	}
}

func newEasyPayWebhookFulfillmentFixture(t *testing.T, initialStatus string) (*PaymentWebhookHandler, *dbent.Client, *dbent.PaymentOrder, string) {
	t.Helper()
	gin.SetMode(gin.TestMode)
	ctx := context.Background()
	db, err := sql.Open("sqlite", fmt.Sprintf("file:easypay_fulfillment_%d?mode=memory&cache=shared", time.Now().UnixNano()))
	require.NoError(t, err)
	t.Cleanup(func() { _ = db.Close() })
	_, err = db.Exec("PRAGMA foreign_keys = ON")
	require.NoError(t, err)
	client := enttest.NewClient(t, enttest.WithOptions(dbent.Driver(entsql.OpenDB(dialect.SQLite, db))))
	t.Cleanup(func() { _ = client.Close() })
	// This adjunct table is maintained by SQL migrations rather than Ent.
	_, err = db.Exec("CREATE TABLE user_blocked_groups (user_id INTEGER NOT NULL, group_id INTEGER NOT NULL, PRIMARY KEY (user_id, group_id))")
	require.NoError(t, err)
	user, err := client.User.Create().SetEmail("payer@example.com").SetPasswordHash("hash").SetBalance(12).Save(ctx)
	require.NoError(t, err)
	userRepo := repository.NewUserRepository(client, db)
	redeemService := service.NewRedeemService(repository.NewRedeemCodeRepository(client), userRepo, nil, nil, nil, client, nil, nil)
	generated, err := redeemService.GenerateRandomCode()
	require.NoError(t, err)
	rechargeCode := "PAY-" + generated
	require.Len(t, rechargeCode, 39)

	config := map[string]string{
		"pid": "1000", "pkey": "test-merchant-key", "apiBase": "https://pay.example.com",
		"notifyUrl": "https://site.example.com/api/v1/payment/webhook/easypay",
		"returnUrl": "https://site.example.com/payment/result", "paymentMode": "popup",
	}
	encryptionKey := []byte("0123456789abcdef0123456789abcdef")
	rawConfig, err := json.Marshal(config)
	require.NoError(t, err)
	encrypted, err := payment.Encrypt(string(rawConfig), encryptionKey)
	require.NoError(t, err)
	instance, err := client.PaymentProviderInstance.Create().SetName("EasyPay").SetProviderKey(payment.TypeEasyPay).
		SetSupportedTypes(payment.TypeAlipay).SetConfig(encrypted).SetEnabled(true).Save(ctx)
	require.NoError(t, err)
	orderBuilder := client.PaymentOrder.Create().SetUserID(user.ID).SetUserEmail(user.Email).SetUserName("payer").
		SetAmount(10).SetPayAmount(10).SetRechargeCode(rechargeCode).SetOutTradeNo("sub2_easypay_fulfillment").
		SetPaymentType(payment.TypeAlipay).SetPaymentTradeNo("").SetOrderType(payment.OrderTypeBalance).
		SetProviderKey(payment.TypeEasyPay).SetProviderInstanceID(strconv.FormatInt(instance.ID, 10)).
		SetStatus(initialStatus).SetExpiresAt(time.Now().Add(time.Hour)).
		SetClientIP("127.0.0.1").SetSrcHost("site.example.com")
	if initialStatus == service.OrderStatusFailed {
		// Model an old order that was paid but failed to create its internal code.
		paidAt := time.Now().Add(-2 * time.Hour)
		orderBuilder.SetPaidAt(paidAt).SetPaymentTradeNo("T1").SetFailedAt(paidAt).
			SetFailedReason("create redeem code: value is greater than the required length")
	}
	order, err := orderBuilder.Save(ctx)
	require.NoError(t, err)
	registry := payment.NewRegistry()
	svc := service.NewPaymentService(client, registry, payment.NewDefaultLoadBalancer(client, encryptionKey), redeemService, nil, nil, userRepo, nil, nil)
	return NewPaymentWebhookHandler(svc, registry), client, order, config["pkey"]
}
