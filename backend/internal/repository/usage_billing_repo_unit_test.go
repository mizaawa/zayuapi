const (
	conditionalBalanceDeductSQL = `(?s)UPDATE users\s+SET balance = balance - \$1,\s+updated_at = NOW\(\)\s+WHERE id = \$2 AND deleted_at IS NULL AND balance >= \$1\s+RETURNING balance`
	overdraftBalanceDeductSQL   = `(?s)UPDATE users\s+SET balance = balance - \$1,\s+updated_at = NOW\(\)\s+WHERE id = \$2 AND deleted_at IS NULL\s+RETURNING balance`
	reserveBatchImageHoldSQL    = `(?s)UPDATE users\s+SET balance = balance - \$1,\s+frozen_balance = COALESCE\(frozen_balance, 0\) \+ \$1,\s+updated_at = NOW\(\)\s+WHERE id = \$2 AND deleted_at IS NULL AND balance >= \$1\s+RETURNING balance, frozen_balance`
	captureBatchImageHoldSQL    = `(?s)UPDATE users\s+SET balance = balance\s+\+ CASE WHEN \$1 > \$2 THEN \$1 - \$2 ELSE 0 END\s+- CASE WHEN \$2 > \$1 THEN \$2 - \$1 ELSE 0 END,\s+frozen_balance = COALESCE\(frozen_balance, 0\) - \$1,\s+updated_at = NOW\(\)\s+WHERE id = \$3 AND deleted_at IS NULL AND COALESCE\(frozen_balance, 0\) >= \$1\s+RETURNING balance, frozen_balance`
	releaseBatchImageHoldSQL    = `(?s)UPDATE users\s+SET balance = balance \+ \$1,\s+frozen_balance = COALESCE\(frozen_balance, 0\) - \$1,\s+updated_at = NOW\(\)\s+WHERE id = \$2 AND deleted_at IS NULL AND COALESCE\(frozen_balance, 0\) >= \$1\s+RETURNING balance, frozen_balance`
	userExistsForBillingSQL     = `(?s)SELECT 1\s+FROM users\s+WHERE id = \$1 AND deleted_at IS NULL`
	usageBillingClaimSQL        = `(?s)INSERT INTO usage_billing_dedup .*RETURNING id`
	usageBillingArchiveSQL      = `(?s)SELECT request_fingerprint\s+FROM usage_billing_dedup_archive\s+WHERE request_id = \$1 AND api_key_id = \$2`
	apiKeyQuotaIncrementSQL     = `(?s)UPDATE api_keys\s+SET quota_used = quota_used \+ \$1,.*WHERE id = \$2 AND deleted_at IS NULL\s+RETURNING`
	apiKeyRateLimitIncrementSQL = `(?s)UPDATE api_keys SET\s+usage_5h = .*WHERE id = \$2 AND deleted_at IS NULL`
	subscriptionIncrementSQL    = `(?s)UPDATE user_subscriptions us\s+SET\s+daily_usage_usd = us.daily_usage_usd \+ \$1,.*WHERE us.id = \$2`
)

func TestUsageBillingRepositoryApply_DeletedAPIKeyStillSettles(t *testing.T) {
	for _, billingMode := range []string{"balance", "subscription"} {
		for _, counters := range []struct {
			name      string
			quota     float64
			rateLimit float64
		}{
			{name: "quota", quota: 10},
			{name: "rate_limit", rateLimit: 10},
			{name: "both", quota: 10, rateLimit: 10},
		} {
			t.Run(billingMode+"/"+counters.name, func(t *testing.T) {
				db, mock, err := sqlmock.New()
				require.NoError(t, err)
				t.Cleanup(func() { _ = db.Close() })

				cmd := &service.UsageBillingCommand{
					RequestID:           "deleted-key-billing",
					APIKeyID:            7,
					UserID:              42,
					APIKeyQuotaCost:     counters.quota,
					APIKeyRateLimitCost: counters.rateLimit,
					ChargedAt:           time.Date(2026, 10, 2, 12, 0, 0, 0, time.UTC),
				}
				if billingMode == "balance" {
					cmd.BalanceCost = 10
				} else {
					subscriptionID := int64(13)
					cmd.SubscriptionID = &subscriptionID
					cmd.SubscriptionCost = 10
				}
				cmd.Normalize()

				mock.ExpectBegin()
				mock.ExpectQuery(usageBillingClaimSQL).
					WithArgs(cmd.RequestID, cmd.APIKeyID, cmd.RequestFingerprint).
					WillReturnRows(sqlmock.NewRows([]string{"id"}).AddRow(1))
				mock.ExpectQuery(usageBillingArchiveSQL).
					WithArgs(cmd.RequestID, cmd.APIKeyID).
					WillReturnError(sql.ErrNoRows)
				if billingMode == "balance" {
					mock.ExpectQuery(conditionalBalanceDeductSQL).
						WithArgs(10.0, cmd.UserID).
						WillReturnRows(sqlmock.NewRows([]string{"balance"}).AddRow(90.0))
				} else {
					mock.ExpectExec(subscriptionIncrementSQL).
						WithArgs(10.0, *cmd.SubscriptionID).
						WillReturnResult(sqlmock.NewResult(0, 1))
				}
				if counters.quota > 0 {
					mock.ExpectQuery(apiKeyQuotaIncrementSQL).
						WithArgs(10.0, cmd.APIKeyID, service.StatusAPIKeyActive, service.StatusAPIKeyQuotaExhausted).
						WillReturnError(sql.ErrNoRows)
				}
				if counters.rateLimit > 0 {
					mock.ExpectExec(apiKeyRateLimitIncrementSQL).
						WithArgs(10.0, cmd.APIKeyID, cmd.ChargedAt).
						WillReturnResult(sqlmock.NewResult(0, 0))
				}
				mock.ExpectCommit()

				result, err := NewUsageBillingRepository(nil, db).Apply(context.Background(), cmd)
				require.NoError(t, err)
				require.True(t, result.Applied)
				require.False(t, result.APIKeyQuotaExhausted)
				if billingMode == "balance" {
					require.NotNil(t, result.NewBalance)
					require.InDelta(t, 90.0, *result.NewBalance, 0.000001)
				}
				require.NoError(t, mock.ExpectationsWereMet())
			})
		}
	}
}

func TestUsageBillingRepositoryApply_APIKeyCounterErrorStillRollsBack(t *testing.T) {
	for _, counter := range []string{"quota", "rate_limit"} {
		t.Run(counter, func(t *testing.T) {
			db, mock, err := sqlmock.New()
			require.NoError(t, err)
			t.Cleanup(func() { _ = db.Close() })

			cmd := &service.UsageBillingCommand{
				RequestID:   "key-counter-error",
				APIKeyID:    7,
				UserID:      42,
				BalanceCost: 10,
				ChargedAt:   time.Date(2026, 10, 2, 12, 0, 0, 0, time.UTC),
			}
			if counter == "quota" {
				cmd.APIKeyQuotaCost = 10
			} else {
				cmd.APIKeyRateLimitCost = 10
			}
			cmd.Normalize()

			mock.ExpectBegin()
			mock.ExpectQuery(usageBillingClaimSQL).
				WithArgs(cmd.RequestID, cmd.APIKeyID, cmd.RequestFingerprint).
				WillReturnRows(sqlmock.NewRows([]string{"id"}).AddRow(1))
			mock.ExpectQuery(usageBillingArchiveSQL).
				WithArgs(cmd.RequestID, cmd.APIKeyID).
				WillReturnError(sql.ErrNoRows)
			mock.ExpectQuery(conditionalBalanceDeductSQL).
				WithArgs(10.0, cmd.UserID).
				WillReturnRows(sqlmock.NewRows([]string{"balance"}).AddRow(90.0))
			if counter == "quota" {
				mock.ExpectQuery(apiKeyQuotaIncrementSQL).
					WithArgs(10.0, cmd.APIKeyID, service.StatusAPIKeyActive, service.StatusAPIKeyQuotaExhausted).
					WillReturnError(sql.ErrConnDone)
			} else {
				mock.ExpectExec(apiKeyRateLimitIncrementSQL).
					WithArgs(10.0, cmd.APIKeyID, cmd.ChargedAt).
					WillReturnError(sql.ErrConnDone)
			}
			mock.ExpectRollback()

			result, err := NewUsageBillingRepository(nil, db).Apply(context.Background(), cmd)
			require.ErrorIs(t, err, sql.ErrConnDone)
			require.Nil(t, result)
			require.NoError(t, mock.ExpectationsWereMet())
		})
	}
}

