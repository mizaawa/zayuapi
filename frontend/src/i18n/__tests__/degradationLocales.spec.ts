function resolve(messages: unknown, path: string): unknown {
  return path.split('.').reduce<unknown>((value, part) => (value && typeof value === 'object' ? (value as Record<string, unknown>)[part] : undefined), messages)
}

describe.each([
  ['zh', zhIndex],
  ['en', enIndex],
])('degradation locale keys (%s)', (_locale, messages) => {
  it('resolves every key to a non-empty translation', () => {
    const missing = keys.filter((key) => {
      const value = resolve(messages, key)
      return typeof value !== 'string' || !value.trim() || value === key
    })
    expect(missing).toEqual([])
  })
})
